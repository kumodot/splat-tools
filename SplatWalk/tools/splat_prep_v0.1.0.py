"""splat_prep - shrink a Gaussian Splat PLY down to something a Quest 3 can walk through.

Part of SplatWalk by Marcelo Souza / Kumodot.art - 2026 // @Msouza3d
Support: https://ko-fi.com/msouza3d

Raw training PLYs are huge because every splat carries 45 spherical-harmonic floats
(73% of the file) that only add view-dependent shine. Dropping those plus an
importance-based decimation typically takes a multi-GB scene down to 50-200 MB
with very little visible loss.

Usage
-----
  # 1. Look before you cut: prints splat count, SH degree, bounding box, size on disk
  python splat_prep_v0.1.0.py scene.ply

  # 2. Make a headset-sized copy (the common case)
  python splat_prep_v0.1.0.py scene.ply -o scene_quest.ply --target 1500000

  # 3. Keep only part of the scene, drop the fog of low-opacity floaters
  python splat_prep_v0.1.0.py scene.ply -o room.ply --crop -5,-2,-5,5,3,5 --min-opacity 0.05

Options
-------
  -o, --out PATH        output PLY (omit to only inspect)
  --target N            keep about N splats, chosen by importance (alpha * size)
  --keep-fraction F     alternative to --target, e.g. 0.25 keeps a quarter
  --keep-sh             keep the spherical harmonics (much bigger file)
  --min-opacity A       drop splats whose alpha is below A (0-1), default 0.02
  --crop x0,y0,z0,x1,y1,z1   keep only splats inside this box (world units)
  --percentile-crop P   auto-crop to the P..100-P percentile of positions, e.g. 1
                        (kills the far-away junk splats that inflate the scene)
  --scale S             multiply all positions and sizes by S
  --stats-only          parse and report, never write (same as omitting -o)

Reads and writes binary_little_endian PLYs and never loads the whole file into RAM,
so a 40 GB input on an 8 GB machine is fine.
"""

import argparse
import os
import sys
import time

VERSION = "0.1.0"

try:
    import numpy as np
except ImportError:
    sys.exit("numpy is required:  pip install numpy")

# Bytes per PLY scalar type
PLY_TYPES = {
    "float": "<f4", "float32": "<f4", "double": "<f8", "float64": "<f8",
    "int": "<i4", "int32": "<i4", "uint": "<u4", "uint32": "<u4",
    "short": "<i2", "int16": "<i2", "ushort": "<u2", "uint16": "<u2",
    "char": "|i1", "int8": "|i1", "uchar": "|u1", "uint8": "|u1",
}
CHUNK = 500_000  # splats per write batch


# ---------------------------------------------------------------------------
# Header
# ---------------------------------------------------------------------------
def read_header(path):
    """Return (count, numpy dtype, data_offset, property_names)."""
    props, count, fmt = [], None, None
    with open(path, "rb") as f:
        if f.readline().strip() != b"ply":
            raise ValueError("not a PLY file")
        in_vertex = False
        while True:
            raw = f.readline()
            if not raw:
                raise ValueError("unexpected end of header")
            line = raw.decode("ascii", "replace").strip()
            parts = line.split()
            if not parts:
                continue
            if parts[0] == "format":
                fmt = parts[1]
            elif parts[0] == "element":
                in_vertex = parts[1] == "vertex"
                if in_vertex:
                    count = int(parts[2])
            elif parts[0] == "property" and in_vertex:
                if parts[1] == "list":
                    raise ValueError("list properties are not supported in the vertex element")
                props.append((parts[2], PLY_TYPES[parts[1]]))
            elif parts[0] == "end_header":
                return count, np.dtype(props), f.tell(), [p[0] for p in props]

    raise ValueError("no end_header found")


def write_header(f, count, dtype):
    f.write(b"ply\nformat binary_little_endian 1.0\n")
    f.write(f"comment generated by splat_prep v{VERSION} - SplatWalk / Kumodot.art\n".encode())
    f.write(f"element vertex {count}\n".encode())
    inv = {v: k for k, v in (("float", "<f4"), ("double", "<f8"), ("int", "<i4"),
                             ("uchar", "|u1"), ("short", "<i2"), ("ushort", "<u2"))}
    for name in dtype.names:
        f.write(f"property {inv.get(dtype[name].str, 'float')} {name}\n".encode())
    f.write(b"end_header\n")


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def sigmoid(x):
    return 1.0 / (1.0 + np.exp(-np.clip(x, -30, 30)))


def human(n):
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{n:.1f} {unit}" if unit != "B" else f"{int(n)} B"
        n /= 1024


def human_count(n):
    if n >= 1e6:
        return f"{n / 1e6:.2f}M"
    if n >= 1e3:
        return f"{n / 1e3:.0f}K"
    return str(n)


def sh_degree(names):
    rest = sum(1 for n in names if n.startswith("f_rest_"))
    return {0: 0, 9: 1, 24: 2, 45: 3}.get(rest, -1), rest


def column(mm, name, count, dtype_out=np.float32):
    """Read one property column from the memmap in chunks (keeps RAM flat)."""
    out = np.empty(count, dtype=dtype_out)
    for i in range(0, count, 4_000_000):
        j = min(i + 4_000_000, count)
        out[i:j] = mm[name][i:j]
    return out


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(add_help=True, description=f"splat_prep v{VERSION}")
    ap.add_argument("input")
    ap.add_argument("-o", "--out")
    ap.add_argument("--target", type=int)
    ap.add_argument("--keep-fraction", type=float)
    ap.add_argument("--keep-sh", action="store_true")
    ap.add_argument("--min-opacity", type=float, default=0.02)
    ap.add_argument("--crop")
    ap.add_argument("--percentile-crop", type=float)
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--stats-only", action="store_true")
    args = ap.parse_args()

    t0 = time.time()
    size = os.path.getsize(args.input)
    count, dtype, offset, names = read_header(args.input)
    deg, n_rest = sh_degree(names)

    print(f"\nsplat_prep v{VERSION}  -  SplatWalk / Kumodot.art")
    print(f"\n{os.path.basename(args.input)}")
    print(f"  size          {human(size)}")
    print(f"  splats        {count:,}  ({human_count(count)})")
    print(f"  bytes/splat   {dtype.itemsize}")
    print(f"  SH degree     {deg if deg >= 0 else '?'}  ({n_rest} f_rest floats"
          f"{f', {n_rest * 4 / dtype.itemsize * 100:.0f}% of the file' if n_rest else ''})")

    mm = np.memmap(args.input, dtype=dtype, mode="r", offset=offset, shape=(count,))

    for req in ("x", "y", "z", "opacity", "scale_0", "rot_0"):
        if req not in names:
            print(f"\n  WARNING: property '{req}' missing. Is this really a Gaussian Splat PLY?")
            break

    print("\n  reading positions...", end="", flush=True)
    xs = column(mm, "x", count)
    ys = column(mm, "y", count)
    zs = column(mm, "z", count)
    raw_opacity = column(mm, "opacity", count)
    print(" done")

    # Real training output almost always contains a handful of NaN/Inf splats.
    # They poison every min/max and percentile, so they are excluded everywhere.
    finite = (np.isfinite(xs) & np.isfinite(ys) & np.isfinite(zs) & np.isfinite(raw_opacity))
    for nm in ("scale_0", "scale_1", "scale_2"):
        if nm in names:
            finite &= np.isfinite(column(mm, nm, count))
    n_bad = int(count - finite.sum())
    if n_bad:
        print(f"  broken        {n_bad} splat(s) with NaN/Inf, they will be dropped")

    fx, fy, fz = xs[finite], ys[finite], zs[finite]
    print(f"  bbox X        {fx.min():9.3f} .. {fx.max():9.3f}")
    print(f"  bbox Y        {fy.min():9.3f} .. {fy.max():9.3f}")
    print(f"  bbox Z        {fz.min():9.3f} .. {fz.max():9.3f}")
    p1 = np.percentile(np.stack([fx, fy, fz]), [1, 99], axis=1)
    print(f"  1-99 pct      X {p1[0][0]:.2f}..{p1[1][0]:.2f}  "
          f"Y {p1[0][1]:.2f}..{p1[1][1]:.2f}  Z {p1[0][2]:.2f}..{p1[1][2]:.2f}")
    print("                (the real scene is roughly this box, the rest is usually stray junk)")
    del fx, fy, fz

    alpha = sigmoid(raw_opacity)
    alpha[~finite] = 0.0
    print(f"  opacity       median {np.median(alpha[finite]):.3f}, "
          f"{(alpha[finite] < args.min_opacity).mean() * 100:.1f}% below {args.min_opacity}")

    if not args.out or args.stats_only:
        est = count * (dtype.itemsize - n_rest * 4)
        print(f"\n  Dropping SH alone would give ~{human(est)}.")
        print(f"  For a Quest 3, aim for 1-2M splats. Suggested:")
        tgt = min(count, 1_500_000)
        print(f"    python {os.path.basename(__file__)} \"{args.input}\" "
              f"-o \"{os.path.splitext(args.input)[0]}_quest.ply\" --target {tgt}")
        print()
        return

    # ---- build the keep mask -------------------------------------------------
    keep = finite & (alpha >= args.min_opacity)

    if args.percentile_crop:
        p = args.percentile_crop
        for arr in (xs, ys, zs):
            lo, hi = np.percentile(arr[finite], [p, 100 - p])
            keep &= (arr >= lo) & (arr <= hi)
        print(f"  percentile crop at {p}%: {keep.sum():,} left")

    if args.crop:
        v = [float(t) for t in args.crop.split(",")]
        if len(v) != 6:
            sys.exit("--crop needs 6 numbers: x0,y0,z0,x1,y1,z1")
        keep &= ((xs >= min(v[0], v[3])) & (xs <= max(v[0], v[3])) &
                 (ys >= min(v[1], v[4])) & (ys <= max(v[1], v[4])) &
                 (zs >= min(v[2], v[5])) & (zs <= max(v[2], v[5])))
        print(f"  box crop: {keep.sum():,} left")

    n_after_filter = int(keep.sum())
    if n_after_filter == 0:
        sys.exit("nothing left after filtering, loosen the crop or --min-opacity")

    target = args.target
    if args.keep_fraction:
        target = int(n_after_filter * args.keep_fraction)

    if target and target < n_after_filter:
        # Importance = how much of the picture this splat is responsible for:
        # its alpha times its average linear size. Keeps the big structural
        # splats and drops the dense speckle first.
        print("  scoring importance...", end="", flush=True)
        s = np.zeros(count, dtype=np.float32)
        for i, nm in enumerate(("scale_0", "scale_1", "scale_2")):
            if nm in names:
                s += column(mm, nm, count)
        s /= 3.0
        imp = alpha * np.exp(np.clip(np.nan_to_num(s, nan=-30.0), -20, 20))
        imp[~keep] = -1.0
        cut = np.argpartition(imp, count - target)[count - target:]
        keep = np.zeros(count, dtype=bool)
        keep[cut] = True
        print(f" done, keeping top {target:,} of {n_after_filter:,}")

    del xs, ys, zs, alpha
    idx = np.flatnonzero(keep)
    n_out = idx.size

    # ---- output dtype --------------------------------------------------------
    out_names = [n for n in dtype.names if args.keep_sh or not n.startswith("f_rest_")]
    out_dtype = np.dtype([(n, dtype[n].str) for n in out_names])
    scale_props = [n for n in ("scale_0", "scale_1", "scale_2") if n in out_names]
    log_scale_shift = np.float32(np.log(args.scale)) if args.scale != 1.0 else None

    print(f"\n  writing {n_out:,} splats x {out_dtype.itemsize} bytes "
          f"= {human(n_out * out_dtype.itemsize)}")
    with open(args.out, "wb") as f:
        write_header(f, n_out, out_dtype)
        for i in range(0, n_out, CHUNK):
            sel = idx[i:i + CHUNK]
            src = mm[sel]                       # only this chunk enters RAM
            buf = np.empty(sel.size, dtype=out_dtype)
            for nm in out_names:
                buf[nm] = src[nm]
            if args.scale != 1.0:
                for nm in ("x", "y", "z"):
                    if nm in out_names:
                        buf[nm] *= args.scale
                for nm in scale_props:          # scales are stored as log
                    buf[nm] += log_scale_shift
            f.write(buf.tobytes())
            done = min(i + CHUNK, n_out)
            print(f"\r  {done * 100 // n_out}%  ({done:,}/{n_out:,})   ", end="", flush=True)

    out_size = os.path.getsize(args.out)
    print(f"\r  100%  ({n_out:,} splats)               ")
    print(f"\n  {args.out}")
    print(f"  {human(size)} -> {human(out_size)}   ({size / max(out_size, 1):.1f}x smaller)"
          f"   in {time.time() - t0:.1f}s")
    if n_out > 2_000_000:
        print("  NOTE: over 2M splats is heavy for a Quest 3. Re-run with a lower --target if it stutters.")
    print()


if __name__ == "__main__":
    main()
